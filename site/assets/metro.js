/* metro.js — обработка результатов измерений: ядро расчётов практикума.
 *
 * Здесь живёт вся арифметика, которой пользуются страница
 * «Обработка результатов измерений» (errors.html) и шесть… двенадцать
 * виртуальных работ v-*.html. Раньше эти формулы были внутри virt-common.js
 * вперемешку с рисованием SVG — из-за чего их нельзя было ни проверить
 * тестом, ни переиспользовать на статической странице. Теперь модуль
 * чистый: не трогает DOM, не читает глобальные переменные, работает и в
 * браузере (window.METRO), и в node (module.exports) — поэтому один и тот
 * же код проверяется тестами tests/test_metro.py.
 *
 * Состав:
 *   1. описательная статистика ряда прямых измерений;
 *   2. коэффициенты Стьюдента и доверительный интервал;
 *   3. суммирование случайной и приборной составляющих;
 *   4. косвенные измерения — перенос погрешности логарифмическим
 *      дифференцированием (общая формула и удобный частный случай степенного
 *      одночлена);
 *   5. метод наименьших квадратов с погрешностями коэффициентов;
 *   6. округление и запись результата по правилам практикума.
 *
 * Самопроверка: METRO.selftest() возвращает массив расхождений (пустой —
 * все контрольные точки сошлись). Контрольные точки взяты не из этого кода,
 * а посчитаны независимо: аналитически (ряды, для которых среднее и СКО
 * считаются в уме), либо по разобранным примерам Зайделя и Тейлора.
 */
'use strict';
(function (root, factory) {
  var api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  if (root) root.METRO = api;
}(typeof globalThis !== 'undefined' ? globalThis : this, function () {

  /* ==================================================================
   *  1. РЯД ПРЯМЫХ ИЗМЕРЕНИЙ
   * ================================================================== */

  /* Среднее арифметическое — наилучшая оценка истинного значения при
     нормальном законе распределения случайной погрешности. */
  function mean(xs) {
    var s = 0, i;
    for (i = 0; i < xs.length; i++) s += xs[i];
    return s / xs.length;
  }

  /* Сумма квадратов отклонений от среднего. Выделена отдельно потому, что
     именно она печатается в отчёте промежуточной строкой. */
  function ss(xs) {
    var m = mean(xs), s = 0, i, d;
    for (i = 0; i < xs.length; i++) { d = xs[i] - m; s += d * d; }
    return s;
  }

  /* Выборочное СКО отдельного измерения (n−1 в знаменателе — оценка
     несмещённая, «поправка Бесселя»). Характеризует разброс приборов и
     условий, а НЕ точность результата. */
  function sd(xs) {
    var n = xs.length;
    return n > 1 ? Math.sqrt(ss(xs) / (n - 1)) : 0;
  }

  /* СКО среднего: во столько же раз меньше, во сколько корень из n.
     Именно эта величина входит в доверительный интервал. */
  function sdMean(xs) {
    var n = xs.length;
    return n > 1 ? Math.sqrt(ss(xs) / (n * (n - 1))) : 0;
  }

  /* ==================================================================
   *  2. КОЭФФИЦИЕНТЫ СТЬЮДЕНТА
   * ================================================================== */

  /* Таблица кафедры физики: строка — доверительная вероятность α,
     столбец — число измерений n (не число степеней свободы!). */
  var T_TABLE = {
    0.9: { 2: 6.3, 3: 2.9, 4: 2.4, 5: 2.1, 6: 2.0, 7: 1.9, 8: 1.9, 9: 1.8, 10: 1.8 },
    0.95: { 2: 12.7, 3: 4.3, 4: 3.2, 5: 2.8, 6: 2.6, 7: 2.4, 8: 2.3, 9: 2.2, 10: 2.2 },
    0.99: { 2: 63.7, 3: 9.9, 4: 5.8, 5: 4.6, 6: 4.0, 7: 3.5, 8: 3.4, 9: 3.3, 10: 3.3 },
  };
  /* предел при n → ∞ — это уже квантили нормального закона */
  var T_INF = { 0.9: 1.6, 0.95: 2.0, 0.99: 2.6 };

  function tStudent(n, alpha) {
    var a = alpha || 0.95;
    var row = T_TABLE[a] || T_TABLE[0.95];
    if (n < 2) return 0;
    if (n <= 10) return row[n];
    /* за таблицей плавно спускаемся к предельному значению: к n = 30
       коэффициент практически равен нормальному квантилю */
    return Math.max(T_INF[a], row[10] - (row[10] - T_INF[a]) * (n - 10) / 20);
  }

  /* ==================================================================
   *  3. ПОЛНАЯ ПОГРЕШНОСТЬ ПРЯМОГО ИЗМЕРЕНИЯ
   * ================================================================== */

  /* Обработка ряда: среднее, СКО, коэффициент Стьюдента, случайная и
     приборная составляющие и их квадратичная сумма.
       xs    — отсчёты;
       instr — приборная (систематическая) погрешность одного отсчёта;
       alpha — доверительная вероятность (по умолчанию 0,95).
     Квадратичное сложение законно потому, что случайная и приборная
     составляющие независимы: складывать их арифметически — значит
     систематически завышать интервал. */
  function series(xs, instr, alpha) {
    var n = xs.length;
    var a = alpha || 0.95;
    var m = mean(xs);
    var s2 = ss(xs);
    var S = n > 1 ? Math.sqrt(s2 / (n - 1)) : 0;
    var Sm = n > 1 ? Math.sqrt(s2 / (n * (n - 1))) : 0;
    var t = tStudent(n, a);
    var dRand = t * Sm;
    var dInstr = instr || 0;
    var d = Math.sqrt(dRand * dRand + dInstr * dInstr);
    return {
      n: n, alpha: a, mean: m, ss: s2, S: S, Sm: Sm, t: t,
      dRand: dRand, dInstr: dInstr, d: d,
      rel: m !== 0 ? d / Math.abs(m) : 0,
    };
  }

  /* ==================================================================
   *  4. КОСВЕННЫЕ ИЗМЕРЕНИЯ
   * ================================================================== */

  /* Общий перенос погрешности: y = f(x1…xk), частные производные считаются
     численно центральной разностью с шагом, привязанным к самой погрешности
     (шаг d/100 — заведомо в области линейности и заведомо больше машинного
     нуля).
       f  — функция от массива аргументов;
       xs — значения аргументов;
       ds — их абсолютные погрешности.
     Возвращает {y, d, terms} — значение, полная погрешность и вклад каждого
     аргумента (именно вклады показывают, что улучшать в опыте). */
  function indirect(f, xs, ds) {
    var y = f(xs.slice());
    var terms = [], sum = 0, i;
    for (i = 0; i < xs.length; i++) {
      var h = Math.abs(ds[i]) / 100;
      if (!(h > 0)) { terms.push(0); continue; }
      var a = xs.slice(), b = xs.slice();
      a[i] = xs[i] + h; b[i] = xs[i] - h;
      var deriv = (f(a) - f(b)) / (2 * h);
      var term = deriv * ds[i];
      terms.push(term);
      sum += term * term;
    }
    var d = Math.sqrt(sum);
    return { y: y, d: d, terms: terms, rel: y !== 0 ? d / Math.abs(y) : 0 };
  }

  /* Частный, но самый ходовой случай: величина — степенной одночлен
     y = C · x1^p1 · x2^p2 · … Тогда относительные погрешности складываются
     квадратично с весами-показателями:
        (Δy/y)² = Σ (pi · Δxi/xi)².
     Это та самая формула «логарифмического дифференцирования», ради которой
     в отчёте сначала логарифмируют рабочую формулу.
       vals  — [{v, d, p}] значение, погрешность, показатель степени;
       y     — уже посчитанное значение результата. */
  function powerLaw(y, vals) {
    var sum = 0, terms = [], i;
    for (i = 0; i < vals.length; i++) {
      var t = vals[i].p * vals[i].d / vals[i].v;
      terms.push(t);
      sum += t * t;
    }
    var rel = Math.sqrt(sum);
    return { y: y, rel: rel, d: rel * Math.abs(y), terms: terms };
  }

  /* ==================================================================
   *  5. МЕТОД НАИМЕНЬШИХ КВАДРАТОВ
   * ================================================================== */

  /* Прямая y = kx + b по методу наименьших квадратов вместе с погрешностями
     коэффициентов. Формулы стандартные (Тейлор, гл. 8):
        k = (n Σxy − Σx Σy) / D,  b = (Σx² Σy − Σx Σxy) / D,  D = n Σx² − (Σx)²,
        S_y² = Σ(yi − k xi − b)² / (n − 2),
        S_k = S_y √(n/D),  S_b = S_y √(Σx²/D).
     Делитель (n − 2), а не (n − 1): две степени свободы уже потрачены на
     подгонку двух коэффициентов.
       pts   — массив [x, y];
       alpha — доверительная вероятность для интервалов коэффициентов.
     Возвращает k, b, их СКО и доверительные полуширины, а также
     коэффициент корреляции r — по нему судят, законна ли сама прямая. */
  function lsq(pts, alpha) {
    var n = pts.length, i;
    var sx = 0, sy = 0, sxx = 0, sxy = 0, syy = 0;
    for (i = 0; i < n; i++) {
      sx += pts[i][0]; sy += pts[i][1];
      sxx += pts[i][0] * pts[i][0];
      sxy += pts[i][0] * pts[i][1];
      syy += pts[i][1] * pts[i][1];
    }
    var D = n * sxx - sx * sx;
    var k = (n * sxy - sx * sy) / D;
    var b = (sxx * sy - sx * sxy) / D;
    var res = 0;
    for (i = 0; i < n; i++) {
      var e = pts[i][1] - k * pts[i][0] - b;
      res += e * e;
    }
    var Sy = n > 2 ? Math.sqrt(res / (n - 2)) : 0;
    var Sk = Sy * Math.sqrt(n / D);
    var Sb = Sy * Math.sqrt(sxx / D);
    /* коэффициент Стьюдента для МНК берётся по числу степеней свободы:
       n − 2 связей, поэтому в таблицу входим с (n − 1) вместо n */
    var t = tStudent(Math.max(2, n - 1), alpha || 0.95);
    var r = (n * sxy - sx * sy)
      / Math.sqrt((n * sxx - sx * sx) * (n * syy - sy * sy));
    return {
      n: n, k: k, b: b, Sy: Sy, Sk: Sk, Sb: Sb, t: t,
      dk: t * Sk, db: t * Sb, r: r,
    };
  }

  /* Прямая через начало координат y = kx (когда физика запрещает свободный
     член: удлинение при нулевой нагрузке равно нулю, путь при нулевом
     времени равен нулю). Здесь k = Σxy/Σx², и степень свободы теряется
     только одна. */
  function lsqThroughOrigin(pts, alpha) {
    var n = pts.length, sxy = 0, sxx = 0, i;
    for (i = 0; i < n; i++) {
      sxy += pts[i][0] * pts[i][1];
      sxx += pts[i][0] * pts[i][0];
    }
    var k = sxy / sxx;
    var res = 0;
    for (i = 0; i < n; i++) {
      var e = pts[i][1] - k * pts[i][0];
      res += e * e;
    }
    var Sy = n > 1 ? Math.sqrt(res / (n - 1)) : 0;
    var Sk = Sy / Math.sqrt(sxx);
    var t = tStudent(n, alpha || 0.95);
    return { n: n, k: k, Sy: Sy, Sk: Sk, t: t, dk: t * Sk };
  }

  /* ==================================================================
   *  6. ОКРУГЛЕНИЕ И ЗАПИСЬ РЕЗУЛЬТАТА
   * ================================================================== */

  /* Правило практикума: погрешность округляется до одной значащей цифры
     (до двух, если первая — 1 или 2), результат — до того же разряда.
     Возвращает округлённую пару и число знаков после запятой. */
  function roundPair(x, d) {
    if (!(d > 0) || !isFinite(d)) return { x: x, d: 0, dec: 3 };
    var e = Math.floor(Math.log10(d) + 1e-12);
    var lead = Math.floor(d / Math.pow(10, e) + 1e-9);
    var keep = lead <= 2 ? 1 : 0;             /* разрядов после старшего */
    var p = Math.pow(10, e - keep);
    var dr = Math.round(d / p) * p;
    if (dr <= 0) dr = p;
    var xr = Math.round(x / p) * p;
    return { x: xr, d: dr, dec: Math.max(0, keep - e) };
  }

  /* Согласуется ли результат с эталонным значением: расхождение меньше
     доверительного интервала — согласуется; меньше двух интервалов —
     «на грани»; больше — промах или систематическая ошибка. */
  function agrees(measured, delta, reference) {
    var dev = Math.abs(measured - reference);
    return { dev: dev, ok: dev <= delta, near: dev <= 2 * delta,
      ratio: delta > 0 ? dev / delta : Infinity };
  }

  /* ==================================================================
   *  САМОПРОВЕРКА
   * ================================================================== */

  function close(a, b, tol) { return Math.abs(a - b) <= (tol || 1e-9) * Math.max(1, Math.abs(b)); }

  function selftest() {
    var bad = [];
    function chk(name, got, want, tol) {
      if (!close(got, want, tol)) bad.push(name + ': получено ' + got + ', ожидалось ' + want);
    }

    /* Ряд, для которого статистика считается в уме: 1, 2, 3, 4, 5.
       Среднее 3, Σ(x−⟨x⟩)² = 4+1+0+1+4 = 10, S = √(10/4) = 1,5811,
       S⟨x⟩ = √(10/20) = 0,7071. */
    var xs = [1, 2, 3, 4, 5];
    chk('среднее ряда 1…5', mean(xs), 3);
    chk('сумма квадратов отклонений', ss(xs), 10);
    chk('СКО измерения', sd(xs), Math.sqrt(2.5));
    chk('СКО среднего', sdMean(xs), Math.sqrt(0.5));

    /* Постоянный ряд: разброса нет, остаётся только приборная погрешность. */
    var st = series([7, 7, 7, 7], 0.1);
    chk('постоянный ряд: случайная часть', st.dRand, 0);
    chk('постоянный ряд: полная погрешность', st.d, 0.1);

    /* Квадратичное сложение: 0,3 и 0,4 дают ровно 0,5. */
    var st2 = series([10, 10.6], 0.4);
    /* ⟨x⟩ = 10,3; S⟨x⟩ = 0,3; t(2; 0,95) = 12,7 → случайная 3,81 */
    chk('СКО среднего для двух отсчётов', st2.Sm, 0.3);
    chk('коэффициент Стьюдента n=2', st2.t, 12.7);
    chk('квадратичное сложение', series([10, 10.6], 0.4).d,
      Math.sqrt(3.81 * 3.81 + 0.16));

    /* Стьюдент монотонно убывает с ростом n и не опускается ниже предела. */
    for (var n = 3; n <= 10; n++) {
      if (tStudent(n, 0.95) > tStudent(n - 1, 0.95)) {
        bad.push('коэффициент Стьюдента не убывает при n = ' + n);
      }
    }
    if (tStudent(1000, 0.95) !== 2.0) bad.push('предел коэффициента Стьюдента не равен 2,0');

    /* МНК на точках, лежащих ТОЧНО на прямой y = 2x + 1: коэффициенты
       обязаны получиться точными, остаточный разброс — нулевым,
       коэффициент корреляции — единичным. */
    var line = [[0, 1], [1, 3], [2, 5], [3, 7], [4, 9]];
    var f = lsq(line);
    chk('МНК: наклон точной прямой', f.k, 2);
    chk('МНК: свободный член точной прямой', f.b, 1);
    chk('МНК: остаточное СКО точной прямой', f.Sy, 0, 1e-6);
    chk('МНК: коэффициент корреляции', f.r, 1, 1e-9);

    /* МНК устойчив к сдвигу начала отсчёта по y: наклон не меняется,
       свободный член сдвигается ровно на величину сдвига. */
    var shifted = line.map(function (p) { return [p[0], p[1] + 10]; });
    var f2 = lsq(shifted);
    chk('МНК: наклон при сдвиге y', f2.k, 2);
    chk('МНК: свободный член при сдвиге y', f2.b, 11);

    /* Прямая через начало: y = 3x. */
    var o = lsqThroughOrigin([[1, 3], [2, 6], [3, 9]]);
    chk('МНК через начало: наклон', o.k, 3);

    /* Косвенное измерение. Объём цилиндра V = πd²h/4 — степенной одночлен,
       поэтому численное дифференцирование и формула показателей обязаны
       дать одно и то же. */
    var d0 = 0.0200, h0 = 0.0500, dd = 0.00005, dh = 0.0001;
    var V = function (a) { return Math.PI * a[0] * a[0] * a[1] / 4; };
    var num = indirect(V, [d0, h0], [dd, dh]);
    var pow = powerLaw(V([d0, h0]), [
      { v: d0, d: dd, p: 2 }, { v: h0, d: dh, p: 1 }]);
    chk('косвенное: численно = аналитически', num.d, pow.d, 1e-6);
    /* и то же самое, посчитанное руками: (2·0,25 %)² + (0,2 %)² → 0,5385 % */
    chk('косвенное: относительная погрешность', pow.rel, Math.sqrt(0.005 * 0.005 + 0.002 * 0.002), 1e-9);

    /* Округление: погрешность с ведущей 1 или 2 сохраняет две цифры,
       остальные — одну; результат подтягивается к тому же разряду. */
    var r1 = roundPair(9.8123, 0.0456);
    chk('округление: погрешность 0,0456 → 0,05', r1.d, 0.05, 1e-9);
    chk('округление: результат к разряду погрешности', r1.x, 9.81, 1e-9);
    var r2 = roundPair(9.8123, 0.0123);
    chk('округление: погрешность 0,0123 → 0,012', r2.d, 0.012, 1e-9);
    chk('округление: результат 9,812', r2.x, 9.812, 1e-9);

    /* Согласие с эталоном. */
    var ag = agrees(9.79, 0.05, 9.81);
    if (!ag.ok) bad.push('согласие с эталоном: расхождение 0,02 при интервале 0,05 должно засчитываться');
    if (agrees(9.60, 0.05, 9.81).near) bad.push('согласие с эталоном: расхождение 0,21 при интервале 0,05 не может быть «на грани»');

    return bad;
  }

  return {
    mean: mean, ss: ss, sd: sd, sdMean: sdMean,
    tStudent: tStudent, series: series,
    indirect: indirect, powerLaw: powerLaw,
    lsq: lsq, lsqThroughOrigin: lsqThroughOrigin,
    roundPair: roundPair, agrees: agrees,
    T_TABLE: T_TABLE, selftest: selftest,
  };
}));
